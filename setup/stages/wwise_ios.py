#!/usr/bin/env python3
"""Optional stage wwise_ios: the Wwise 2019.2.15 iOS sound engine for the iOS build (Audiokinetic's files are not shipped with this
repository - only our .meta files and this script are).

Source = Unity.iOS.tar.xz of the Wwise Unity Integration 2019.2.15.7667.2215 (Audiokinetic Launcher bundle
unityintegration.2019_2_15_2215, sha1 83b5b85fb7ed5434e0f1963ef3636791ad03a2fb), or the folder it was extracted into.
It must match the engine the arm64 fork's macOS AkSoundEngine.bundle is (2019.2.15) - the C# side below is that macOS binding.

  1 lib       Wwise/Deployment/Plugins/iOS/Release/libAkSoundEngine.a, arm64 slice only (lipo; the tarball's is arm64 + armv7).
              Release = no profiler comms on the phone. Wwise's AkPluginActivator enables only the folder of the current plug-in
              config (none set = Profile): BdspWinBuild.iOS.cs switches it to Release for the iOS player build and restores it.
              All the plug-ins the banks use (PluginInfo.xml: ParametricEQ, RoomVerb, Flanger, Meter, DefaultSink) and the Vorbis
              decoder are built into this lib and registered by it (AkSoundEngineStubs.cpp) - no DSP/*.a, no AkiOSPlugins.cpp.
  2 bindings  Wwise/Deployment/API/Generated/iOS/*_iOS.cs = the project's Generated/Mac/*_Mac.cs (2019.2.4 SWIG output the port
              already runs against the 2019.2.15 engine) with the #if guard -> UNITY_IOS && !UNITY_EDITOR and DllImport
              "AkSoundEngine" -> "__Internal" (IL2CPP static link). The 2019.2.15 iOS binding differs from its macOS one only by 12
              optional AVAudioSession accessors (not used: defaults = SoloAmbient). Every EntryPoint is checked against the lib's
              exported symbols: a missing one would be an Xcode link error.
  3 bank path AkBasePathGetter.GetPlatformBasePath on iOS starts from PcPlatform.PcPaths.StreamingAssets (the app's Documents
              copy first, the app's own StreamingAssets otherwise) instead of Application.streamingAssetsPath. The banks
              (StreamingAssets/Audio/GeneratedSoundBanks/iOS) are APFS clones of the Mac ones, made by the iOS player step.

  python -I setup/stages/wwise_ios.py [--source <Unity.iOS.tar.xz | folder with Wwise/Deployment/Plugins/iOS>] [--check]
--check: report what is installed / stale, change nothing (exit 1 if anything is missing).

The description above is the 2019.2.4 common integration (the existing working tree; that path is unchanged). When the installed
common code is 2019.2.15 (Assets/Wwise/Version.txt, e.g. from the offline package) no binding is derived from Mac: the archive's
own Generated/iOS (__Internal, same SWIG generation as 2019.2.15 Common) is installed as shipped, together with the platform
scripts 2019.2.15 moved out of Common: Handwritten/iOS/AkSoundEngine.cs, AkiOSBasePathGetter.cs and
Editor/EditorPlatformHelpers/iOS/AkiOSPluginActivator.cs. AkiOSSettings.cs and the iOS menu are not installed (the working build
uses the global initialization settings; see wwise_android.py). Every entry point is checked against the thinned arm64 lib's
exports and every shared AkSoundEnginePINVOKE call must resolve in the binding.
"""
