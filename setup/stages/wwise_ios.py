def guid(rel):
    return hashlib.md5(("bdsp-wwise-ios:" + rel).encode()).hexdigest()


def rel(p):
    return os.path.relpath(p, paths.ASSETS).replace(os.sep, "/")


def write_if_changed(path, data, check, report):
    data = data.encode("utf-8") if isinstance(data, str) else data
    old = open(path, "rb").read() if os.path.exists(path) else None
    if old == data:
        return True
    report.append(("missing " if old is None else "stale ") + rel(path))
    if not check:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)
    return False


def sha1(path):
    h = hashlib.sha1()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 22), b""):
            h.update(b)
    return h.hexdigest()


def run(cmd):
    p = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if p.returncode:
        sys.exit("failed (%d): %s\n%s" % (p.returncode, " ".join(cmd), p.stdout[-2000:]))
    return p.stdout


def source_lib(source, tmp):
    """The tarball's (fat) Release libAkSoundEngine.a: from the extracted folder, else extracted from the tarball."""
    if os.path.isdir(source):
        p = os.path.join(source, TAR_LIB)
        if not os.path.isfile(p):
            sys.exit("no %s under %s" % (TAR_LIB, source))
        return p
    if not os.path.isfile(source):
        sys.exit("no Wwise iOS integration at %s (Unity.iOS.tar.xz of Wwise Unity Integration 2019.2.15 - Audiokinetic Launcher)" % source)
    got = sha1(source)
    if got != TAR_SHA1:
        sys.exit("%s: sha1 %s, expected %s (Unity_2019.2.15.7667.2215 Unity.iOS.tar.xz)" % (source, got, TAR_SHA1))
    print("extracting %s from %s ..." % (TAR_LIB, source))
    run(["tar", "-xJf", source, "-C", tmp, TAR_LIB])
    return os.path.join(tmp, TAR_LIB)


def install_lib(source, check, report):
    meta_ok = all([write_if_changed(os.path.join(WWISE, "Deployment", "Plugins", "iOS.meta"),
                                    FOLDER_META % guid("Plugins/iOS"), check, report),
                   write_if_changed(os.path.join(WWISE, "Deployment", "Plugins", "iOS", "Release.meta"),
                                    FOLDER_META % guid("Plugins/iOS/Release"), check, report),
                   write_if_changed(LIB + ".meta", LIB_META % guid("Plugins/iOS/Release/libAkSoundEngine.a"), check, report)])
    if check:
        if not os.path.isfile(LIB):
            report.append("missing " + rel(LIB))
            return False
        return meta_ok
    with tempfile.TemporaryDirectory(prefix="wwise_ios_") as tmp:
        fat = source_lib(source, tmp)
        thin = os.path.join(tmp, "libAkSoundEngine.a")
        run(["lipo", fat, "-thin", "arm64", "-output", thin])
        if os.path.isfile(LIB) and sha1(LIB) == sha1(thin):
            print("lib up to date: %s" % rel(LIB))
            return meta_ok
        os.makedirs(os.path.dirname(LIB), exist_ok=True)
        shutil.copyfile(thin, LIB)
        report.append("installed " + rel(LIB))
    print("lib: %s (%.0f MB, %s)" % (rel(LIB), os.path.getsize(LIB) / 1e6, run(["lipo", "-info", LIB]).strip().split(": ")[-1]))
    return meta_ok


def exported_symbols():
    # stdout only: nm also writes to stderr, and the two interleaved in one pipe garble lines (a real symbol went missing)
    p = subprocess.run(["nm", "-gU", LIB], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True)
    if p.returncode:
        sys.exit("nm -gU %s failed (%d)" % (LIB, p.returncode))
    out = p.stdout
    return set(m.group(1) for m in re.finditer(r" T _(CSharp_\w+)$", out, re.M))


def install_bindings(check, report):
    ok = write_if_changed(GEN_IOS + ".meta", FOLDER_META % guid("API/Generated/iOS"), check, report)
    exports = exported_symbols() if os.path.isfile(LIB) else None
    for c in CLASSES:
        src = os.path.join(GEN_MAC, c + "_Mac.cs")
        text = open(src, encoding="utf-8-sig").read()
        if text.count(MAC_GUARD) != 2 or not text.startswith(MAC_GUARD):
            sys.exit("%s: expected the macOS #if guard on the first line and in the closing #endif comment" % rel(src))
        text = text.replace(MAC_GUARD, IOS_GUARD)
        if c == "AkSoundEnginePINVOKE":
            n = text.count('DllImport("AkSoundEngine"')
            if n == 0 or n != text.count("DllImport("):
                sys.exit("%s: %d DllImport(\"AkSoundEngine\") of %d DllImport" % (rel(src), n, text.count("DllImport(")))
            text = text.replace('DllImport("AkSoundEngine"', 'DllImport("__Internal"')
            imports = set(re.findall(r'EntryPoint="(CSharp_\w+)"', text))
            if exports is not None:
                missing = sorted(imports - exports)
                if missing:
                    sys.exit("the iOS libAkSoundEngine.a does not export %d entry points the binding imports: %s"
                             % (len(missing), ", ".join(missing[:20])))
                print("bindings: %d entry points, all exported by the iOS lib (%d CSharp_* exports)" % (len(imports), len(exports)))
        lines = text.split("\n", 1)
        text = lines[0] + "\n" + HEADER % c + lines[1]
        dst = os.path.join(GEN_IOS, c + "_iOS.cs")
        ok &= write_if_changed(dst, text, check, report)
        ok &= write_if_changed(dst + ".meta", SCRIPT_META % guid("API/Generated/iOS/" + c + "_iOS.cs"), check, report)
    return ok


TAR_GEN = "Wwise/Deployment/API/Generated/iOS"
PLATFORM_2019_2_15 = ["Deployment/API/Handwritten/iOS/AkSoundEngine.cs", "Deployment/API/Handwritten/iOS/AkiOSBasePathGetter.cs",
                      "Editor/EditorPlatformHelpers/iOS/AkiOSPluginActivator.cs"]
EXCLUDED_2019_2_15 = {"Deployment/API/Handwritten/iOS/AkiOSSettings.cs": "AkiOSSettings",
                      "Editor/WwiseMenu/iOS/AkWwiseMenu_iOS.cs": "AkWwiseMenu_iOS"}


def source_scripts_2019_2_15(source, tmp):
    """Folder holding Wwise/... with Generated/iOS + the platform scripts (extracted folder, or safely from the verified tarball)."""
    if os.path.isdir(source):
        if not os.path.isdir(os.path.join(source, TAR_GEN)):
            sys.exit("no %s under %s" % (TAR_GEN, source))
        return source
    if not os.path.isfile(source):
        sys.exit("no Wwise iOS integration at %s (Unity.iOS.tar.xz of Wwise Unity Integration 2019.2.15 - Audiokinetic Launcher)" % source)
    if sha1(source) != TAR_SHA1:
        sys.exit("%s: sha1 differs from %s (Unity_2019.2.15.7667.2215 Unity.iOS.tar.xz)" % (source, TAR_SHA1))
    import wwise_offline
    out = os.path.join(tmp, "scripts")
    print("extracting Generated/iOS + platform scripts from %s ..." % source, flush=True)
    try:
        wwise_offline.safe_extract(source, out, lambda r: r.startswith((TAR_GEN + "/",) + tuple(
            "Wwise/" + p.rsplit("/", 1)[0] + "/" for p in PLATFORM_2019_2_15)) and r.endswith(".cs"))
    except wwise_offline.PackageError as e:
        sys.exit(str(e))
    return out


def guarded(text):
    m = re.search(r"^\s*#if\b(.*)$", text, re.M)
    return bool(m and "UNITY_EDITOR" in m.group(1))


def install_2019_2_15(tree, check, report):
    """Vendor-coherent 2019.2.15 iOS bindings + platform scripts (tree None = check what is installed)."""
    ok = write_if_changed(GEN_IOS + ".meta", FOLDER_META % guid("API/Generated/iOS"), check, report)
    exports = exported_symbols() if os.path.isfile(LIB) else None
    gen_dir = os.path.join(tree, TAR_GEN) if tree is not None else GEN_IOS
    names = sorted(f for f in os.listdir(gen_dir) if f.endswith("_iOS.cs")) if os.path.isdir(gen_dir) else []
    if not names:
        report.append("missing bindings under " + rel(GEN_IOS))
        return False
    pinvoke = None
    for name in names:
        data = open(os.path.join(gen_dir, name), "rb").read()
        text = data.decode("utf-8-sig")
        if not re.match(r"#if\b[^\n]*UNITY_IOS", text):
            sys.exit("%s: expected the iOS #if guard on the first line" % name)
        if "AkiOSSettings" in text:
            sys.exit("%s references AkiOSSettings, which this stage deliberately does not install" % name)
        if name == "AkSoundEnginePINVOKE_iOS.cs":
            pinvoke = text
            if text.count("DllImport(") != text.count('DllImport("__Internal"'):
                sys.exit("%s: every DllImport must be __Internal for the static iOS engine" % name)
        dst = os.path.join(GEN_IOS, name)
        ok &= write_if_changed(dst, data, check, report)
        ok &= write_if_changed(dst + ".meta", SCRIPT_META % guid("API/Generated/iOS/" + name), check, report)
    if pinvoke is None:
        sys.exit("no AkSoundEnginePINVOKE_iOS.cs in Generated/iOS")
    imports = set(re.findall(r'EntryPoint\s*=\s*"(CSharp_\w+)"', pinvoke))
    if len(imports) < 1000:
        sys.exit("AkSoundEnginePINVOKE_iOS.cs: only %d native entry points; not a genuine generated binding" % len(imports))
    if exports is not None:
        missing = sorted(imports - exports)
        if missing:
            sys.exit("the iOS libAkSoundEngine.a does not export %d entry points the binding imports: %s" % (len(missing), ", ".join(missing[:20])))
        print("bindings: %d entry points, all exported by the iOS lib (%d CSharp_* exports)" % (len(imports), len(exports)))
    for rel_path in PLATFORM_2019_2_15:
        src = os.path.join(tree, "Wwise", rel_path) if tree is not None else os.path.join(WWISE, rel_path)
        if not os.path.isfile(src):
            report.append("missing " + rel_path)
            ok = False
            continue
        data = open(src, "rb").read()
        text = data.decode("utf-8-sig")
        if not guarded(text):
            sys.exit("%s: platform script without a UNITY_EDITOR-aware #if guard; it would collide with the Mac editor partials" % rel_path)
        for excluded, cls in EXCLUDED_2019_2_15.items():
            if re.search(r"\b%s\b" % cls, text):
                sys.exit("%s references %s, which this stage deliberately does not install (%s)" % (rel_path, cls, excluded))
        dst = os.path.join(WWISE, rel_path)
        ok &= write_if_changed(dst, data, check, report)
        parts = rel_path.split("/")
        for i in range(2, len(parts)):       # new folders only; an existing tracked folder .meta is never rewritten
            folder = "/".join(parts[:i])
            if not os.path.exists(os.path.join(WWISE, folder + ".meta")):
                ok &= write_if_changed(os.path.join(WWISE, folder + ".meta"), FOLDER_META % guid(folder + "/"), check, report)
        ok &= write_if_changed(dst + ".meta", SCRIPT_META % guid(rel_path), check, report)
    defined = set(re.findall(r"static (?:extern )?[\w.:<>]+ (CSharp_\w+)\(", pinvoke))
    called = set()
    for root in (os.path.join(WWISE, "Deployment", "API", "Generated", "Common"), os.path.join(WWISE, "Deployment", "API", "Handwritten"),
                 os.path.join(WWISE, "Deployment", "Components")):
        for d, _, files in os.walk(root):
            if os.sep + "Handwritten" + os.sep in d + os.sep and os.path.basename(d) in ("Android", "Mac", "Windows"):
                continue
            for f in files:
                if f.endswith(".cs"):
                    called |= set(re.findall(r"AkSoundEnginePINVOKE\.(CSharp_\w+)", open(os.path.join(d, f), encoding="utf-8-sig").read()))
    unresolved = sorted(called - defined)
    if unresolved:
        sys.exit("shared Wwise code calls %d AkSoundEnginePINVOKE entries the iOS binding lacks: %s" % (len(unresolved), ", ".join(unresolved[:20])))
    print("bindings: all %d AkSoundEnginePINVOKE calls of the shared Wwise code resolve" % len(called))
    return ok


def patch_basepath(check, report):
    text = open(BASEPATH, encoding="utf-8-sig").read()
    if BASEPATH_NEW in text or BASEPATH_ANDROID in text:   # wwise_android.py widens the iOS block to iOS || Android: still patched
        return True
    if text.count(BASEPATH_OLD) != 1:
        sys.exit("cannot patch %s: the streamingAssetsPath block found %d times" % (rel(BASEPATH), text.count(BASEPATH_OLD)))
    report.append(("unpatched " if check else "patched ") + rel(BASEPATH) + " (iOS banks via PcPaths.StreamingAssets)")
    if not check:
        raw = open(BASEPATH, "rb").read()
        bom = b"\xef\xbb\xbf" if raw.startswith(b"\xef\xbb\xbf") else b""
        with open(BASEPATH, "wb") as f:
            f.write(bom + text.replace(BASEPATH_OLD, BASEPATH_NEW).encode("utf-8"))
    return False


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", default=os.environ.get("BDSP_WWISE_IOS") or DEFAULT_SOURCE)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if not os.path.isdir(GEN_MAC):
        sys.exit("no %s: install the Wwise integration first (setup/stages/wwise.py)" % GEN_MAC)
    family = wwise.version_info(WWISE)[0]
    common_ok = wwise.apply_patches(WWISE, check=a.check, unity6=True, family=family)
    report = []
    ok = install_lib(a.source, a.check, report)
    if family == "2019.2.15":
        with tempfile.TemporaryDirectory(prefix="wwise_ios_scripts_") as tmp:
            ok &= install_2019_2_15(None if a.check else source_scripts_2019_2_15(a.source, tmp), a.check, report)
    else:
        ok &= install_bindings(a.check, report)
    ok &= patch_basepath(a.check, report)
    ok &= common_ok
    for line in report:
        print("  " + line)
    if a.check:
        print("wwise_ios: " + ("installed, up to date" if ok else "NOT installed / stale - run: python -I setup/stages/wwise_ios.py"))
        return 0 if ok else 1
    print("wwise_ios: done (%d change(s))" % len(report))
    return 0


if __name__ == "__main__":
    sys.exit(main())
